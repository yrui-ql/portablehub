// Feature-scoped tables are merged here so each feature owns its own file and
// parallel work never touches this one.
const en: Record<string, string> = { ...enBase, ...enEdit, ...enSettings, ...enDiscover, ...enMigrate }
const zhCN: Record<string, string> = { ...zhBase, ...zhEdit, ...zhSettings, ...zhDiscover, ...zhMigrate }

const tables: Record<string, Record<string, string>> = { 'zh-CN': zhCN, en }

export function makeT(locale: string): Translator {
  const table = tables[locale] ?? zhCN
  return (key, vars) => {
    let text = table[key] ?? key
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        text = text.split(`{${name}}`).join(String(value))
      }
    }
    return text
  }
}

